"""Print the turn service's pins: every distribution its install and its tests resolve to here, as installed.

    .venv/bin/python scripts/service_constraints.py > service/constraints.txt

Run it in the environment the service's tests pass in (Python 3.12, as CI and the hosted image use). It walks
``Requires-Dist`` from ``kernel-turns``, with the markers this interpreter gives, plus ``pytest`` and ``pytest-asyncio``,
and prints ``name==version`` for each distribution it reaches, ``kernel-turns`` itself left out. Anything else in the
environment (the writer, linters) is not in the set. It stops on an editable or local install inside the set: a pin
must be something pip can fetch.
"""

from __future__ import annotations

import json
import sys
from importlib import metadata

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

SERVICE = "kernel-turns"
ROOTS = [SERVICE, "pytest", "pytest-asyncio"]


def _wanted(requirement: Requirement, extras: frozenset[str]) -> bool:
    if requirement.marker is None:
        return True
    return any(requirement.marker.evaluate({"extra": extra}) for extra in extras or {""})


def _local(dist: metadata.Distribution) -> bool:
    raw = dist.read_text("direct_url.json")
    if not raw:
        return False
    url = json.loads(raw)
    return bool(url.get("dir_info", {}).get("editable")) or str(url.get("url", "")).startswith("file:")


def main() -> int:
    pins: dict[str, str] = {}
    seen: set[tuple[str, frozenset[str]]] = set()
    todo: list[tuple[str, frozenset[str]]] = [(root, frozenset()) for root in ROOTS]
    while todo:
        name, extras = todo.pop()
        key = canonicalize_name(name)
        if (key, extras) in seen:
            continue
        seen.add((key, extras))
        dist = metadata.distribution(name)
        if key != SERVICE:
            if _local(dist):
                print(f"{key} is an editable or local install: it cannot be pinned", file=sys.stderr)
                return 1
            pins[key] = dist.version
        for raw in dist.requires or []:
            requirement = Requirement(raw)
            if _wanted(requirement, extras):
                todo.append((requirement.name, frozenset(requirement.extras)))
    print("# The turn service's dependencies as its tests pass with them. Generated by scripts/service_constraints.py:")
    print("# do not edit by hand. CI's service job and the hosted image install with -c service/constraints.txt.")
    for key in sorted(pins):
        print(f"{key}=={pins[key]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
